-- New Life Hospital, Indore - Ujjain Rd : core relational schema (PostgreSQL)

CREATE SEQUENCE patient_code_seq START WITH 1001 INCREMENT BY 1;
CREATE SEQUENCE invoice_number_seq START WITH 1 INCREMENT BY 1;

-- 1. Credentials for both staff and administrators
CREATE TABLE users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(30)  NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(10)  NOT NULL,
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    token_version  INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'STAFF'))
);

-- 2. Staff profile, one per user account
CREATE TABLE staff_profiles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT       NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(120),
    phone_number  VARCHAR(15),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_staff_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_staff_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- 3. Validation metadata shared by the Angular client and the Spring server
CREATE TABLE field_validations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_name      VARCHAR(50)  NOT NULL,
    field_name     VARCHAR(50)  NOT NULL,
    field_label    VARCHAR(80)  NOT NULL,
    data_type      VARCHAR(20)  NOT NULL,
    required       BOOLEAN      NOT NULL DEFAULT FALSE,
    regex_pattern  VARCHAR(500),
    min_length     INTEGER,
    max_length     INTEGER,
    error_message  VARCHAR(255) NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_field_validations UNIQUE (form_name, field_name),
    CONSTRAINT ck_field_validations_type CHECK (data_type IN ('STRING', 'NUMBER', 'DECIMAL', 'DATE', 'EMAIL', 'PHONE')),
    CONSTRAINT ck_field_validations_len CHECK (min_length IS NULL OR max_length IS NULL OR min_length <= max_length)
);

-- 4. Doctors shown on the public site and selectable for OPD evaluation
CREATE TABLE doctors (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(100) NOT NULL,
    specialization    VARCHAR(100) NOT NULL,
    qualification     VARCHAR(150),
    experience_years  INTEGER,
    photo_url         VARCHAR(255),
    is_active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_doctors_experience CHECK (experience_years IS NULL OR experience_years BETWEEN 0 AND 70)
);

-- 5. Patients. Government ID numbers are stored AES-256-GCM encrypted; an HMAC-SHA256
--    blind index (id_number_hash) enforces uniqueness and allows exact-match duplicate lookup.
CREATE TABLE patients (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_code     VARCHAR(20)  NOT NULL,
    name             VARCHAR(100) NOT NULL,
    id_type          VARCHAR(20)  NOT NULL,
    id_type_other    VARCHAR(50),
    id_number        VARCHAR(512) NOT NULL,
    id_number_hash   VARCHAR(64)  NOT NULL,
    id_number_last4  VARCHAR(4)   NOT NULL,
    dob              DATE         NOT NULL,
    gender           VARCHAR(10)  NOT NULL,
    contact_number   VARCHAR(15)  NOT NULL,
    address          VARCHAR(255),
    created_by       VARCHAR(30)  NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_patients_code UNIQUE (patient_code),
    CONSTRAINT uq_patients_id_hash UNIQUE (id_number_hash),
    CONSTRAINT ck_patients_id_type CHECK (id_type IN ('AADHAAR', 'PASSPORT', 'VOTER_ID', 'DRIVING_LICENSE', 'OTHER')),
    CONSTRAINT ck_patients_other CHECK (id_type <> 'OTHER' OR id_type_other IS NOT NULL),
    CONSTRAINT ck_patients_gender CHECK (gender IN ('MALE', 'FEMALE', 'OTHER'))
);
CREATE INDEX ix_patients_name ON patients (name);
CREATE INDEX ix_patients_contact ON patients (contact_number);

-- 6. Charges master
CREATE TABLE hospital_services (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_name  VARCHAR(120)   NOT NULL,
    category      VARCHAR(60)    NOT NULL,
    cost          NUMERIC(12, 2) NOT NULL,
    description   VARCHAR(500),
    is_active     BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_hospital_services_name UNIQUE (service_name),
    CONSTRAINT ck_hospital_services_cost CHECK (cost >= 0)
);

-- 7. Invoices. invoice_date is the hospital-local (Asia/Kolkata) calendar date used for revenue reports.
CREATE TABLE invoices (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number  VARCHAR(30)    NOT NULL,
    patient_id      BIGINT         NOT NULL,
    staff_username  VARCHAR(30)    NOT NULL,
    staff_name      VARCHAR(100)   NOT NULL,
    doctor_id       BIGINT,
    total_amount    NUMERIC(12, 2) NOT NULL,
    discount        NUMERIC(12, 2) NOT NULL DEFAULT 0,
    net_amount      NUMERIC(12, 2) NOT NULL,
    paid_amount     NUMERIC(12, 2) NOT NULL,
    balance_amount  NUMERIC(12, 2) NOT NULL,
    payment_status  VARCHAR(10)    NOT NULL,
    invoice_date    DATE           NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_invoices_number UNIQUE (invoice_number),
    CONSTRAINT fk_invoices_patient FOREIGN KEY (patient_id) REFERENCES patients (id),
    CONSTRAINT fk_invoices_doctor FOREIGN KEY (doctor_id) REFERENCES doctors (id),
    CONSTRAINT ck_invoices_status CHECK (payment_status IN ('PARTIAL', 'FULL')),
    CONSTRAINT ck_invoices_amounts CHECK (
        total_amount >= 0 AND discount >= 0 AND discount <= total_amount
        AND net_amount = total_amount - discount
        AND paid_amount >= 0 AND balance_amount >= 0
        AND paid_amount + balance_amount = net_amount)
);
CREATE INDEX ix_invoices_patient ON invoices (patient_id);
CREATE INDEX ix_invoices_date ON invoices (invoice_date);

-- 8. Invoice line items (service name and unit price are snapshotted at billing time)
CREATE TABLE invoice_items (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id    BIGINT         NOT NULL,
    service_id    BIGINT         NOT NULL,
    service_name  VARCHAR(120)   NOT NULL,
    unit_price    NUMERIC(12, 2) NOT NULL,
    quantity      INTEGER        NOT NULL,
    amount        NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_invoice_items_invoice FOREIGN KEY (invoice_id) REFERENCES invoices (id) ON DELETE CASCADE,
    CONSTRAINT fk_invoice_items_service FOREIGN KEY (service_id) REFERENCES hospital_services (id),
    CONSTRAINT ck_invoice_items_qty CHECK (quantity BETWEEN 1 AND 999),
    CONSTRAINT ck_invoice_items_amount CHECK (amount = unit_price * quantity)
);
CREATE INDEX ix_invoice_items_invoice ON invoice_items (invoice_id);

-- 9. CMS text blocks for the public website
CREATE TABLE cms_content (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_key   VARCHAR(60)   NOT NULL,
    label         VARCHAR(100)  NOT NULL,
    content_text  VARCHAR(4000) NOT NULL,
    updated_by    VARCHAR(30),
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_cms_section UNIQUE (section_key)
);
